export function localeCopy(raw: string | undefined): Copy {
  const lang = normalizeLang(raw)
  if (typeof document !== 'undefined') {
    document.documentElement.lang = htmlLang(lang)
    document.documentElement.dir = htmlDir(lang)
  }
  return Object.fromEntries(keys.map((key, i) => [key, translations[lang][i]])) as Copy
}

export function errorText(copy: Copy, error: unknown): string {
  const key = error instanceof Error ? error.message : ''
  if (key === 'presentationTooLarge') return copy.tooLarge
  if (key === 'encryptedPresentation') return copy.encrypted
  if (key === 'invalidText') return copy.invalidText
  if (key === 'readOnly') return copy.readOnly
  return copy.error
}
