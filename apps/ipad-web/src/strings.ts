export function stringsFor(locale: string): { lang: Lang; text: Strings } {
  const lang = normalizeLang(locale)
  const text =
    lang === 'en'
      ? en
      : (Object.fromEntries(Object.keys(en).map((key, i) => [key, rows[lang][i]])) as Strings)
  return { lang, text }
}
